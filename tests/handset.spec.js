import {test,expect} from '@playwright/test'

const phone=page=>page.locator('#match-phone')
const key=(page,name)=>phone(page).getByRole('button',{name,exact:true})
const open=(page,id)=>phone(page).locator('[data-app='+id+']').click()
const home=page=>key(page,'Phone Home').click()
const tile=(page,square)=>page.locator('#grid [data-square='+square+']')

test.beforeEach(async({page})=>{
  await page.addInitScript(()=>{
    if(!localStorage.getItem('evolution-settings'))localStorage.setItem('evolution-settings',JSON.stringify({
      quality:'low',camera:'flat',reduced:true,
    }))
    if(!localStorage.getItem('evolution-handset-puzzle-numbers'))
      localStorage.setItem('evolution-handset-puzzle-numbers',JSON.stringify({board:[2,2,...Array(14).fill(0)],score:0,tray:[]}))
  })
})

test('home, separate media apps, music, settings, recent apps and lock work',async({page})=>{
  const failures=[]
  page.on('pageerror',error=>failures.push(error.message))
  await page.route('https://www.youtube.com/iframe_api',route=>route.abort())
  await page.goto('/?view=match')
  await page.getByRole('button',{name:'Open Side Reel phone',exact:true}).click()
  await expect(phone(page).locator('.handset-app')).toHaveCount(16)
  await open(page,'youtube')
  await expect(phone(page).locator('.phone-header strong')).toHaveText('YouTube Shorts')
  await phone(page).getByLabel('YouTube URL').fill('https://www.youtube.com/shorts/-eNe1OmbbXc')
  await key(page,'Add link').click()
  await key(page,'Favourite').click()
  await expect(key(page,'Favourite')).toHaveAttribute('aria-pressed','true')
  await key(page,'Load YouTube player').click()
  await expect(phone(page).getByRole('status')).toContainText('YouTube could not connect')
  await expect(phone(page).getByRole('link',{name:'Open video on YouTube'})).toHaveAttribute('href','https://www.youtube.com/shorts/-eNe1OmbbXc')
  await home(page)
  await open(page,'comedy')
  await expect(phone(page).locator('.phone-header strong')).toHaveText('AI Shorts')
  const before=await phone(page).locator('canvas').evaluate(canvas=>canvas.toDataURL())
  const initial=await phone(page).locator('.comedy-title+p').textContent()
  await key(page,'Play short').click()
  await expect.poll(()=>phone(page).locator('progress').evaluate(bar=>bar.value)).toBeGreaterThan(2.8)
  expect(await phone(page).locator('canvas').evaluate(canvas=>canvas.toDataURL())).not.toBe(before)
  await key(page,'Generate 3 shorts').click()
  await expect(phone(page).locator('.comedy-title+p')).not.toHaveText(initial)
  await expect(phone(page).locator('progress')).toHaveAttribute('value','0')
  await home(page)
  await open(page,'music')
  await key(page,'Play track').click()
  await expect(key(page,'Pause track')).toBeVisible()
  await key(page,'Add to playlist').click()
  await home(page)
  await key(page,'Recent apps').click()
  await expect(key(page,'Music')).toBeVisible()
  await key(page,'Music').click()
  await expect(key(page,'Pause track')).toBeVisible()
  await expect(key(page,'Remove from playlist')).toBeVisible()
  await key(page,'Pause track').click()
  await home(page)
  await open(page,'settings')
  await phone(page).getByLabel('Wallpaper').selectOption('ocean')
  await phone(page).getByLabel('Frame finish').selectOption('titanium')
  await phone(page).getByLabel('Display mode').selectOption('light')
  await phone(page).getByLabel('Screen side').selectOption('left')
  await phone(page).getByLabel('Lock when reopened').check()
  await key(page,'Phone Home').click()
  await key(page,'Arrange').click()
  await key(page,'Move AI Shorts earlier').click()
  await key(page,'Done').click()
  await key(page,'Lock phone').click()
  await expect(key(page,'Unlock')).toBeVisible()
  await key(page,'Unlock').click()
  await key(page,'Close phone').click()
  await page.keyboard.press('p')
  await expect(key(page,'Unlock')).toBeVisible()
  await key(page,'Unlock').click()
  await expect(phone(page)).toHaveAttribute('data-wallpaper','ocean')
  await expect(phone(page)).toHaveAttribute('data-mode','light')
  await expect(phone(page).locator('.handset-app').first()).toHaveAttribute('data-app','comedy')
  await expect(page.locator('.game-layout')).toHaveAttribute('data-phone-side','left')
  await key(page,'Close phone').click()
  await page.reload()
  await page.getByRole('button',{name:'Open Side Reel phone',exact:true}).click()
  await expect(phone(page)).toHaveAttribute('data-frame','titanium')
  expect(failures).toEqual([])
})

test('arcade runs, saved puzzles, and chess input stay independent',async({page})=>{
  await page.goto('/?view=match')
  await page.getByRole('button',{name:'Open Side Reel phone',exact:true}).click()
  for(const [id,action] of [['wings','Flap'],['snake','Start'],['runner','Jump'],['tower','Place block'],['racing','Drive']]){
    await open(page,id)
    await expect(phone(page).locator('canvas')).toBeVisible()
    await key(page,action).click()
    if(id==='tower')await expect(phone(page).locator('.arcade-score strong').first()).toHaveText(/[1-9]/)
    if(id==='snake')await expect.poll(()=>page.evaluate(()=>localStorage.getItem('evolution-handset-best-snake'))).toBe('1')
    await key(page,'Restart').click()
    await expect(phone(page).locator('.arcade-status')).toHaveText('Ready')
    await home(page)
  }
  await open(page,'numbers')
  await key(page,'Slide left').click()
  await expect(phone(page).locator('.arcade-score strong').first()).toHaveText('4')
  await expect(phone(page).locator('[data-value="4"]').first()).toBeVisible()
  await tile(page,'e2').click()
  await tile(page,'e4').click()
  await expect(tile(page,'e4')).toHaveAttribute('aria-label','e4 white Pawn')
  await expect(key(page,'Resume')).toBeVisible()
  await key(page,'Minimize phone').click()
  await page.keyboard.press('p')
  await expect(phone(page).locator('.arcade-score strong').first()).toHaveText('4')
  await home(page)
  await open(page,'blocks')
  await key(page,'Shape 1').click()
  await key(page,'Row 1, column 1').click()
  await expect(phone(page).locator('.handset-puzzle-tile.tile-active').first()).toBeVisible()
  await home(page)
  await open(page,'chess')
  await phone(page).getByLabel('Choose chess puzzle').selectOption('puzzle-0')
  await phone(page).locator('[data-puzzle-square=e1]').click()
  await phone(page).locator('[data-puzzle-square=e8]').click()
  await expect(phone(page).locator('.arcade-status')).toContainText('Solved')
  await expect(phone(page).locator('.handset-note')).toContainText('Solved 1')
  await key(page,'Close phone').click()
  await expect(tile(page,'e4')).toHaveAttribute('aria-label','e4 white Pawn')
})
