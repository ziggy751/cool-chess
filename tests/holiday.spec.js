import {test,expect} from '@playwright/test'
const button=(page,name)=>page.getByRole('button',{name,exact:true})
const tile=(page,square)=>page.locator('[data-square='+square+']')
const nav=(page,name)=>page.locator('.main-nav').getByRole('button',{name,exact:true})
const play=(page)=>page.locator('#match-phone video').evaluate(video=>video.play())
const paused=(page)=>page.locator('#match-phone video').evaluate(video=>video.paused)
const move=async(page,from,to)=>{await tile(page,from).click();await tile(page,to).click()}

test.beforeEach(async({page})=>page.addInitScript(()=>{
  if(!localStorage.getItem('evolution-settings'))localStorage.setItem('evolution-settings',JSON.stringify({quality:'low',reduced:true,camera:'flat'}))
}))

test('the Christmas menu and all four room previews load with real geometry',async({page})=>{
  test.setTimeout(155000)
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  page.on('console',message=>{if(message.type()==='error' && /THREE|GL_INVALID/.test(message.text()))errors.push(message.text())})
  await page.goto('/')
  await button(page,'Christmas menu').dispatchEvent('click')
  await expect(page.locator('#webgl')).toHaveAttribute('data-world','christmas-cabin')
  await button(page,'Christmas menu').dispatchEvent('click')
  await expect(page.locator('#webgl')).toHaveAttribute('data-world','cabin')
  await nav(page,'Collection').dispatchEvent('click')
  await button(page,'Environments').dispatchEvent('click')
  const group=page.getByLabel('Filter collection')
  await group.selectOption('Christmas')
  await expect(page.locator('.catalog-pick')).toHaveCount(4)
  for(const [label,id] of [['Luxury Christmas Cabin','christmas-cabin'],['Santa’s Workshop','christmas-workshop'],
    ['Christmas Village','christmas-village'],['Northern Lights Christmas','christmas-aurora']]){
    await button(page,label).dispatchEvent('click')
    await expect(page.locator('#webgl')).toHaveAttribute('data-world',id)
    await expect(page.locator('#webgl canvas')).toBeVisible()
  }
  await button(page,'Piece sets').dispatchEvent('click')
  await group.selectOption('Christmas')
  await expect(page.locator('.catalog-pick')).toHaveCount(8)
  await button(page,'Snow Globe').dispatchEvent('click')
  await button(page,'White pieces').dispatchEvent('click')
  await expect(page.locator('#webgl')).toHaveAttribute('data-camera','specimen')
  await button(page,'Chessboards').dispatchEvent('click')
  await group.selectOption('Christmas')
  await expect(page.locator('.catalog-pick')).toHaveCount(6)
  expect(errors).toEqual([])
})

test('playing a clip leaves the AI match responsive and pauses on return of the turn',async({page})=>{
  await page.goto('/')
  await button(page,'Play vs AI').click()
  await page.getByLabel('Difficulty',{exact:true}).selectOption('0')
  await page.getByLabel('Thinking time').selectOption('3000')
  await button(page,'Start game').click()
  await button(page,'Open Side Reel phone').click()
  await expect(page.locator('#match-phone')).toBeVisible()
  await page.locator('#match-phone [data-app=clips]').click()
  await button(page,'Play video').click()
  await expect.poll(()=>paused(page)).toBe(false)
  const time=await page.locator('#match-phone video').evaluate(video=>video.currentTime)
  await expect.poll(()=>page.locator('#match-phone video').evaluate(video=>video.currentTime)).toBeGreaterThan(time)
  await move(page,'e2','e4')
  await expect(page.locator('#turn-banner')).toContainText('Your turn',{timeout:25000})
  await expect.poll(()=>paused(page)).toBe(true)
  await expect(tile(page,'e4')).toHaveAttribute('aria-label','e4 white Pawn')
  await button(page,'Bookmark video').click()
  await page.getByLabel('Video category').selectOption('saved')
  await expect(page.locator('.phone-video-copy strong')).toHaveText('Winter window')
  await button(page,'Phone Home').click()
  await page.locator('#match-phone [data-app=settings]').click()
  await page.getByLabel('Screen side').selectOption('left')
  await expect(page.locator('.game-layout')).toHaveAttribute('data-phone-side','left')
  await button(page,'Minimize phone').click()
  await expect(page.locator('#match-phone')).toBeHidden()
  await page.keyboard.press('p')
  await expect(page.locator('#match-phone')).toBeVisible()
  await expect(page.locator('.game-layout')).toHaveAttribute('data-phone-side','left')
  await button(page,'Phone Home').click()
  await page.locator('#match-phone [data-app=clips]').click()
  await page.locator('#phone-file').setInputFiles('public/side-reel/aurora.mp4')
  await expect(page.locator('.phone-video-copy strong')).toHaveText('aurora.mp4')
  await play(page)
  await button(page,'Close phone').click()
  await expect.poll(()=>paused(page)).toBe(true)
})

test('a private match continues across phone playback and never exposes analysis or chess clips',async({browser})=>{
  test.setTimeout(125000)
  const first=await browser.newContext(),second=await browser.newContext()
  try{
    for(const context of [first,second])await context.addInitScript(()=>localStorage.setItem('evolution-settings',
      JSON.stringify({quality:'low',reduced:true,camera:'flat',coaching:'detailed'})))
    const white=await first.newPage(),black=await second.newPage()
    await white.goto('/')
    await nav(white,'Multiplayer').click()
    await white.getByLabel('Play as').selectOption('w')
    await button(white,'Create room').click()
    await expect(white.locator('#turn-banner')).toContainText('Waiting for opponent')
    await black.goto(white.url())
    await expect(black.locator('#turn-banner')).toContainText('Opponent’s turn')
    await nav(black,'Analysis').click()
    await expect(black.locator('#toast')).toContainText('Analysis is available after the match finishes')
    await button(black,'Open Side Reel phone').click()
    await expect(black.locator('#match-phone [data-app=youtube]').first()).toBeDisabled()
    await black.locator('#match-phone [data-app=clips]').click()
    await expect(black.locator('#phone-category option[value=Chess]')).toHaveCount(0)
    await expect(black.locator('#phone-file')).toBeDisabled()
    await button(black,'Play video').click()
    await expect.poll(()=>paused(black)).toBe(false)
    await move(white,'e2','e4')
    await expect(black.locator('#turn-banner')).toContainText('Your turn')
    await expect.poll(()=>paused(black)).toBe(true)
    await move(black,'e7','e5')
    await expect(tile(white,'e5')).toHaveAttribute('aria-label','e5 black Pawn')
    await button(black,'Close phone').click()
    await move(white,'g1','f3')
    await expect(tile(black,'f3')).toHaveAttribute('aria-label','f3 white Knight')
    await expect(black.locator('#analysis-meter')).toBeHidden()
  }finally{await first.close();await second.close()}
})
