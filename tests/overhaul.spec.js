import { test, expect } from '@playwright/test'

test.beforeEach(async ({page}) => {
  await page.addInitScript(() => {
    if(!localStorage.getItem('evolution-settings')) localStorage.setItem('evolution-settings',JSON.stringify({reduced:true,quality:'low'}))
  })
})

const button=(page,name)=>page.getByRole('button',{name,exact:true})
const setting=(page,name)=>page.locator('.main-nav').getByRole('button',{name,exact:true})
const move=async(page,from,to)=>{
  await page.locator('[data-square="'+from+'"]').click()
  await page.locator('[data-square="'+to+'"]').click()
}

test('showroom previews setups and stores a separate model for one piece',async({page})=>{
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  page.on('console',msg=>{if(msg.type()==='error' && /THREE|GL_INVALID/.test(msg.text()))errors.push(msg.text())})
  await page.goto('/')
  await setting(page,'Collection').click()
  await expect(page.locator('.catalog-card')).toHaveCount(53)
  await page.getByRole('searchbox',{name:'Search collection'}).fill('Living Marble')
  await button(page,'Living Marble').click()
  await button(page,'Favourite Living Marble').click()
  await page.getByLabel('Filter collection').selectOption('favorites')
  await expect(page.locator('.catalog-card')).toHaveCount(1)
  await button(page,'White pieces').click()
  await button(page,'Knight').click()
  await page.locator('[data-edit=collection]').selectOption('mechanical')
  await page.locator('[data-edit=material]').selectOption('brass')
  await page.getByText('Advanced material',{exact:true}).click()
  await page.locator('[data-edit=engraving]').selectOption('diamond')
  await button(page,'Show board').click()
  await button(page,'Chessboards').click()
  await page.getByRole('searchbox',{name:'Search collection'}).fill('Volcanic')
  await button(page,'Volcanic basalt').click()
  await button(page,'Animations').click()
  await button(page,'Crystal dissolve').click()
  await button(page,'Effects').click()
  await button(page,'Crystal shards').click()
  await button(page,'Saved presets').click()
  await page.getByLabel('Preset name').fill('Foundry')
  await button(page,'Save preset').click()
  const data=await page.evaluate(()=>JSON.parse(localStorage.getItem('evolution-presets'))[0])
  expect(data.styles.overrides.w).toEqual({n:{collection:'mechanical',material:'brass',engraving:'diamond'}})
  expect(data.styles.theme).toBe('lava')
  expect(data.styles.motion).toBe('dissolve')
  expect(data.styles.effect).toBe('crystal')
  await page.reload()
  await setting(page,'Collection').click()
  await button(page,'Saved presets').click()
  await expect(button(page,'Foundry')).toBeVisible()
  expect(errors).toEqual([])
})

test('ranked AI survives reload and records a resignation only once',async({page})=>{
  await page.addInitScript(()=>{if(!localStorage.getItem('evolution-settings'))localStorage.setItem('evolution-settings',JSON.stringify({reduced:true,quality:'low'}))})
  await page.goto('/')
  await button(page,'Play chess').click()
  await button(page,'Ranked AI').click()
  await expect(page.locator('#current-ai-elo')).toHaveText('0 Elo')
  await button(page,'Play Ranked AI').click()
  await expect(page.locator('#match-type')).toHaveText('Ranked AI')
  await expect(button(page,'New game')).toBeDisabled()
  await page.reload()
  await expect(page.locator('#match-type')).toHaveText('Ranked AI')
  await button(page,'Resign').click()
  await button(page,'Confirm resignation').click()
  await expect(page.getByRole('heading',{name:'Defeat'})).toBeVisible()
  const ladder=await page.evaluate(()=>JSON.parse(localStorage.getItem('evolution-ai-ladder')))
  expect(ladder.rating).toBe(0)
  expect(ladder.losses).toBe(1)
  expect(ladder.history[0].opponent).toBeLessThanOrEqual(50)
  expect(ladder.played).toBe(1)
  expect(ladder.active).toBeNull()
  await page.reload()
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('evolution-ai-ladder')).played)).toBe(1)
})

